const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const DEFAULT_INPUT_PATH = path.join(projectRoot, 'initial-admin.private.json');
const DEFAULT_OUTPUT_PATH = path.join(
  projectRoot,
  'electron',
  'generated',
  'initialAdminCredential.cjs',
);

function readPrivateCredential(inputPath) {
  if (!fs.existsSync(inputPath)) {
    throw new Error('INITIAL_ADMIN_CREDENTIAL_FILE_NOT_FOUND');
  }

  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
  } catch {
    throw new Error('INITIAL_ADMIN_CREDENTIAL_FILE_INVALID_JSON');
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('INITIAL_ADMIN_CREDENTIAL_FILE_INVALID');
  }

  const username = typeof parsed.username === 'string' ? parsed.username.trim() : '';
  if (!username) throw new Error('INITIAL_ADMIN_USERNAME_REQUIRED');

  const password = typeof parsed.password === 'string' ? parsed.password : '';
  if (password.length < 8 || !password.trim()) {
    throw new Error('INITIAL_ADMIN_PASSWORD_TOO_SHORT');
  }

  const credentialVersion = parsed.credentialVersion === undefined
    ? '1'
    : typeof parsed.credentialVersion === 'string'
      ? parsed.credentialVersion.trim()
      : '';
  if (!credentialVersion) {
    throw new Error('INITIAL_ADMIN_CREDENTIAL_VERSION_REQUIRED');
  }

  return { username, password, credentialVersion };
}

function prepareInitialAdminCredential({
  inputPath = DEFAULT_INPUT_PATH,
  outputPath = DEFAULT_OUTPUT_PATH,
  randomBytes = crypto.randomBytes,
} = {}) {
  const { username, password, credentialVersion } = readPrivateCredential(inputPath);
  const passwordSalt = randomBytes(16).toString('hex');
  const passwordHash = crypto.scryptSync(password, passwordSalt, 64).toString('hex');
  const generatedCredential = {
    username,
    passwordSalt,
    passwordHash,
    credentialVersion,
  };
  const source = [
    "'use strict';",
    '',
    '// Generated by scripts/prepare-initial-admin-credential.cjs. Do not edit.',
    `module.exports = ${JSON.stringify(generatedCredential, null, 2)};`,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, source, 'utf8');
  return generatedCredential;
}

if (require.main === module) {
  try {
    prepareInitialAdminCredential();
    console.log(`Initial administrator credential digest generated: ${DEFAULT_OUTPUT_PATH}`);
  } catch (error) {
    console.error(`Initial administrator credential preparation failed: ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = {
  DEFAULT_INPUT_PATH,
  DEFAULT_OUTPUT_PATH,
  prepareInitialAdminCredential,
  readPrivateCredential,
};

